КОРЕНЬ = Path(__file__).resolve().parent
БЛОКИ = КОРЕНЬ / "блоки_выигрыш"
ИСХОД = ("есть", "нет")

# понятие-область, имя блока, корзины, размер вектора, соль
ЯДРА = {
    "А": [("деления:нет", "Выигрыш_А_без_делений", 2048, 48, "В-А1"),
          ("деления:есть", "Выигрыш_А_с_делениями", 4096, 48, "В-А2")],
    "Б": [("память:много", "Выигрыш_Б_много_памяти", 1536, 64, "В-Б1"),
          ("память:мало", "Выигрыш_Б_мало_памяти", 3072, 64, "В-Б2")],
}


def граница(dag, model) -> int:
    from vliw.core.dag import compute_metrics
    m = compute_metrics(dag, model)
    return max(m.critical_path_bound, m.resource_bound)


def токены_с_зазором(токены: list[str], зазор: int) -> list[str]:
    return токены + [f"зазор_жадного:{min(зазор, 8)}"]


def подготовить(метки: list[dict]) -> tuple[list[dict], int]:
    """Строки для обучения/оценки: только там, где жадный НЕ на границе (иначе решает правило).

    Возвращает (строки, сколько графов отсеяло правило).
    """
    from vliw.core.model import get_profile
    from vliw.tiny.features import build_dag, parse_graph_entries

    model = get_profile("e2k-v6-measured")
    язык = ЯзыкГрафов()
    out, правило = [], 0
    for m in метки:
        dag = build_dag(parse_graph_entries(m["prompt"]))
        зазор = m["по_группам"]["greedy"] - граница(dag, model)
        if зазор <= 0:
            правило += 1
            continue
        t = язык.перевести(m["prompt"])
        out.append({"ключ": m["ключ"], "n": m["n"], "лучший": m["лучший"], "по_группам": m["по_группам"],
                    "дешёвая": m["дешёвая"], "токены": токены_с_зазором(t["токены"], зазор),
                    "понятия": t["понятия"], "зазор": зазор})
    return out, правило


def ответ_id(область: str, исход: str) -> str:
    return f"{область}/выигрыш:{исход}"


def исход_из_ответа(ответ: str) -> str:
    return ответ.rsplit(":", 1)[1]


def область_строки(ядро: str, понятия: dict) -> str:
    for обл, *_ in ЯДРА[ядро]:
        if понятия.get(обл) == 1.0:
            return обл
    raise ValueError(f"строка не попала ни в одну область ядра {ядро}: {понятия}")


def описание_блоков(ядро: str) -> list[dict]:
    обл = [o for o, *_ in ЯДРА[ядро]]
    return [{"имя": имя, "область": o, "корзины": B, "размер": d, "соль": соль,
             "пишет": [o], "читает": [x for x in обл if x != o],
             "ответы": [ответ_id(o, и) for и in ИСХОД]}
            for o, имя, B, d, соль in ЯДРА[ядро]]


def метка(r: dict) -> str:
    """«есть» — портфель крошек нашёл расписание короче жадного."""
    return "есть" if r["лучший"] < r["по_группам"]["greedy"] else "нет"


def строки_ядра(ядро: str, база: list[dict]) -> list[dict]:
    out = []
    for r in база:
        обл = область_строки(ядро, r["понятия"])
        и = метка(r)
        out.append({"токены": r["токены"], "понятия": r["понятия"], "группа": и,
                    "ответы": [ответ_id(обл, и)], "ключ": r["ключ"]})
    return out


def разбить(база: list[dict], доля_dev: float = 0.15, зерно: int = 1):
    """Обучение/dev: все «есть» и столько же «нет» (иначе ядро выучит «всегда нет»)."""
    rnd = random.Random(зерно)
    есть = [r for r in база if метка(r) == "есть"]
    нет = [r for r in база if метка(r) == "нет"]
    rnd.shuffle(нет)
    пул = есть + нет[:len(есть)]
    tr, dv = [], []
    for исход in ИСХОД:
        rows = [r for r in пул if метка(r) == исход]
        rnd.shuffle(rows)
        k = max(1, int(доля_dev * len(rows)))
        dv += rows[:k]
        tr += rows[k:]
    rnd.shuffle(tr)
    rnd.shuffle(dv)
    return tr, dv


def обучить_ядро(ядро: str, tr_база, dv_база, зерно: int, выход: Path, сведения: dict) -> dict:
    опис = описание_блоков(ядро)
    блоки = [С.БлокУч(о["имя"], о["ответы"], о["пишет"], о["читает"], корзины=о["корзины"], размер=о["размер"],
                      граница=ГРАНИЦА, соль=о["соль"], seed=зерно * 100 + i, область=о["область"],
                      роль=f"есть ли выигрыш у поиска на графах «{о['область']}»", свёртка=СВЁРТКА,
                      масштаб_чтения=МАСШТАБ)
             for i, о in enumerate(опис)]
    tr = С.Набор(строки_ядра(ядро, tr_база), блоки, ВСЕ_ПОНЯТИЯ)
    dv = С.Набор(строки_ядра(ядро, dv_база), блоки, ВСЕ_ПОНЯТИЯ)
    сеть = С.Сеть(блоки, проходов=2, смешивание="среднее", градиент_через_шину=False, шум_шины=0.0)
    папка = выход / ядро
    папка.mkdir(parents=True, exist_ok=True)
    cfg = НАСТРОЙКИ_ОБУЧЕНИЯ
    итог = С.обучить(сеть, tr, dv, эпох=cfg["эпох"], терпение=cfg["терпение"], пакет=cfg["пакет"], lr=cfg["lr"],
                     λ=cfg["λ"], p_выходной=0.0, seed=зерно, журнал=str(папка / "обучение.jsonl"), имя=f"ядро {ядро}")
    язык = ЯзыкГрафов().паспорт_языка()
    for b, о in zip(блоки, опис):
        bd = папка / b.имя
        bd.mkdir(parents=True, exist_ok=True)
        w = bd / "веса.npz"
        b.сохранить(str(w))
        паспорт = {
            "имя": b.имя, "версия": 1, "роль": b.роль, "область": о["область"], "архитектура": "мешок_шина",
            "настройки": {"корзины": b.B, "размер": b.d, "граница": b.L, "соль": b.соль, "свёртка": b.свёртка,
                          "масштаб_чтения": b.масштаб},
            "веса": {"файл": "веса.npz", "sha256": sha256_файла(w), "чисел": b.чисел()},
            "язык": язык, "пишет": b.пишет, "читает": b.читает, "ответы": b.ответы,
            "проекции": {a: {о["область"]: 16.0} for a in b.ответы},
            "обучение": {"скрипт": "nnl_vliw/выигрыш.py", "ядро": ядро, "зерно": зерно,
                         "когда": datetime.now().isoformat(timespec="seconds"), "данные": сведения,
                         "эпох": итог["эпох"], "лучший_dev": итог["лучший_dev"], "настройки": cfg,
                         "вместе_с": [x.имя for x in блоки if x is not b]},
        }
        (bd / "паспорт.json").write_text(json.dumps(паспорт, ensure_ascii=False, indent=1), encoding="utf-8")
    (папка / "ход_обучения.json").write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    return итог


# ---------------------------------------------------------------- применение

@lru_cache(maxsize=1)
def _ядра() -> tuple[Матплата, Матплата]:
    язык = ЯзыкГрафов()
    return загрузить_ядро(БЛОКИ / "А", язык), загрузить_ядро(БЛОКИ / "Б", язык)


def доступно() -> bool:
    return (БЛОКИ / "А").is_dir() and (БЛОКИ / "Б").is_dir()


def _решить(p: dict):
    """(исход|None, p выбранного, p(есть)) по вероятностям ядра. None — «не знаю»."""
    есть = sum(v for k, v in p.items() if k != "ничего" and исход_из_ответа(k) == "есть")
    k = max(p, key=p.get)
    if k == "ничего":
        return None, p[k], есть
    return исход_из_ответа(k), p[k], есть


def по_токенам(токены: list[str]) -> dict:
    """{'А': (исход, p, p_есть), 'Б': (...), 'p_есть': среднее двух ядер, 'итог': ...}."""
    A, Б = _ядра()
    рез = {имя: _решить(вероятности(плата, токены)) for имя, плата in (("А", A), ("Б", Б))}
    а, б = рез["А"][0], рез["Б"][0]
    рез["p_есть"] = (рез["А"][2] + рез["Б"][2]) / 2
    # итог: ядра согласны — вердикт; иначе «не знаю» (искать как обычно)
    рез["итог"] = а if (а is not None and а == б) else None
    return рез


def оценить(dag, model, жадный: int | None = None) -> dict:
    """Правило, потом ядра. `жадный` — makespan baseline (если не дан, считается здесь).

    Если жадный на нижней границе — {"итог": "нет", "правило": True}: нейросеть не спрашивается,
    это доказательство. Иначе — ответ ядер с зазором в токенах.
    """
    if жадный is None:
        from vliw.core.baseline import GreedyListScheduler
        жадный = GreedyListScheduler().schedule(dag, model).schedule.makespan
    lb = граница(dag, model)
    зазор = жадный - lb
    if зазор <= 0:
        return {"итог": "нет", "правило": True, "зазор": 0, "p_есть": 0.0,
                "А": ("нет", 1.0, 0.0), "Б": ("нет", 1.0, 0.0)}
    токены, _ = токены_графа(dag, model)
    r = по_токенам(токены_с_зазором(токены, зазор))
    r["правило"] = False
    r["зазор"] = зазор
    return r


# ---------------------------------------------------------------- оценка на наборах

def оценка_набора(база: list[dict]) -> dict:
    """Честная таблица по набору меток: сколько «есть» нашли и сколько тревог ложных."""
    n = len(база)
    истина = [метка(r) for r in база]
    пред = [по_токенам(r["токены"]) for r in база]
    есть = sum(1 for и in истина if и == "есть")
    out = {"графов": n, "с_выигрышем": есть}
    for имя, f in (("ядро А", lambda p: p["А"][0]), ("ядро Б", lambda p: p["Б"][0]),
                   ("согласие ядер", lambda p: p["итог"])):
        ответы = [f(p) for p in пред]
        tp = sum(1 for a, и in zip(ответы, истина) if a == "есть" and и == "есть")
        fp = sum(1 for a, и in zip(ответы, истина) if a == "есть" and и == "нет")
        fn = sum(1 for a, и in zip(ответы, истина) if a == "нет" and и == "есть")
        tn = sum(1 for a, и in zip(ответы, истина) if a == "нет" and и == "нет")
        нз = sum(1 for a in ответы if a is None)
        out[имя] = {"нашёл_выигрыш": tp, "ложная_тревога": fp, "пропустил_выигрыш": fn,
                    "верно_«нет»": tn, "не_знаю": нз}
    return out


def печать(имя: str, o: dict) -> None:
    print(f"\n== {имя}: правило границы сняло {o.get('отсеяно_правилом_границы', 0)} графов (выигрыша там нет, "
          f"доказано); дальше решают ядра на {o['графов']}, из них с выигрышем {o['с_выигрышем']}")
    print(f"   {'':16}{'нашёл':>8}{'ложных':>8}{'пропустил':>11}{'верно нет':>11}{'не знаю':>9}")
    for k in ("ядро А", "ядро Б", "согласие ядер"):
        v = o[k]
        print(f"   {k:16}{v['нашёл_выигрыш']:>8}{v['ложная_тревога']:>8}{v['пропустил_выигрыш']:>11}"
              f"{v['верно_«нет»']:>11}{v['не_знаю']:>9}")


def main() -> int:
    for _s in (sys.stdout, sys.stderr):
        try:
            _s.reconfigure(errors="replace", encoding="utf-8")
        except Exception:  # noqa: BLE001
            pass
    ap = argparse.ArgumentParser(description="Ядра NNL «есть ли что улучшать»")
    ap.add_argument("команда", choices=("обучить", "оценка"))
    ap.add_argument("--метки", required=True, help="папка с *.labels.jsonl")
    ap.add_argument("--выход", default=str(БЛОКИ))
    ap.add_argument("--зерно", type=int, default=1)
    ap.add_argument("--наборы", default="eval_hard,eval_wide,eval_real")
    ap.add_argument("--json", default="")
    a = ap.parse_args()
    t0 = time.time()
    if a.команда == "обучить":
        метки = []
        for p in sorted(Path(a.метки).glob("train_*.labels.jsonl")):
            метки += Д.прочитать_метки(p)
        база, правило = подготовить(метки)
        tr, dv = разбить(база, зерно=a.зерно)
        сведения = {"графов_в_метках": len(метки), "отсеяно_правилом_границы": правило,
                    "с_зазором": len(база), "с_выигрышем": sum(1 for r in база if метка(r) == "есть"),
                    "обучение": len(tr), "dev": len(dv), "зерно": a.зерно, "метка": "портфель короче жадного"}
        print("данные:", json.dumps(сведения, ensure_ascii=False), "%.0f с" % (time.time() - t0), flush=True)
        for i, я in enumerate(("А", "Б")):
            обучить_ядро(я, tr, dv, a.зерно * 10 + i + 1, Path(a.выход), сведения)
        print("готово за %.0f с" % (time.time() - t0))
        return 0
    рез = {}
    for имя in a.наборы.split(","):
        путь = Path(a.метки) / f"{имя}.labels.jsonl"
        if not путь.exists():
            print("нет набора", путь)
            continue
        база, правило = подготовить(Д.прочитать_метки(путь))
        рез[имя] = оценка_набора(база)
        рез[имя]["отсеяно_правилом_границы"] = правило
        печать(имя, рез[имя])
    if a.json:
        Path(a.json).write_text(json.dumps(рез, ensure_ascii=False, indent=1), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
