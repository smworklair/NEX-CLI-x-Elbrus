def _softmax(логиты: dict) -> dict:
    import math
    m = max(логиты.values())
    e = {k: math.exp(v - m) for k, v in логиты.items()}
    z = sum(e.values())
    return {k: v / z for k, v in e.items()}


def загрузить(папка: Path, язык):
    плата = Матплата(язык, str(ARCH))
    for bd in sorted(p for p in папка.iterdir() if (p / "паспорт.json").exists()):
        ok, res = плата.подключить(str(bd))
        if not ok:
            raise RuntimeError(f"{bd.name}: {res}")
    return плата


def ответ_платы(плата, токены: list[str]):
    блоки = list(плата.блоки.values())
    запись: dict = {}
    for b in блоки:
        for k, v in b.arch.проход1(b.obj, токены).items():
            запись.setdefault(k, []).append(v)
    шина = {k: sum(v) / len(v) for k, v in запись.items()}
    логиты = {"ничего": 0.0}
    for b in блоки:
        логиты.update(b.arch.проход2(b.obj, токены, шина))
    p = _softmax(логиты)
    return О.решение(p)


def предложения(незнакомые, плата_имя, плата_упот) -> list[dict]:
    ряды = []
    for r in незнакомые:
        ка, иа, па = ответ_платы(плата_имя, r["токены_имени"])
        кб, иб, пб = ответ_платы(плата_упот, r["токены_употребления"])
        согласие = Ц.перекрёсток(ка, кб)
        if согласие is not None:
            предложен = согласие
            уверенность = round(min(па, пб), 4)
            пометка = ""
        else:
            # Не принимаем: расхождение или «ничего». В таблице всё равно видно, кто что сказал.
            if ка is not None and (кб is None or па >= пб):
                предложен = ка
                уверенность = round(па, 4)
            elif кб is not None:
                предложен = кб
                уверенность = round(пб, 4)
            else:
                предложен = ""
                уверенность = round(max(па, пб), 4)
            пометка = "проверить ассемблером"
        ряды.append({
            "мнемоника": r["мнемоника"], "встреч": r["встреч"],
            "предложенный_класс": предложен, "уверенность": уверенность,
            "ядро_имя": ка or "ничего", "p_имя": round(па, 4),
            "ядро_употребление": кб or "ничего", "p_употребление": round(пб, 4),
            "пометка": пометка,
        })
    return ряды


def _md_предложения(ряды_мн, ряды_лат) -> str:
    lines = [
        "# Предложения: 13 незнакомых мнемоник и допущения латентности",
        "",
        "Это предложения. `MNEMONICS` и `vliw/core/model.py` не менялись.",
        "Согласие ядер — предложенный класс без пометки. Расхождение или «ничего» — «проверить ассемблером»;",
        "в этом случае класс в колонке — тот, у кого выше вероятность, и он не принят.",
        "",
        "| мнемоника | встреч | предложенный класс | уверенность | ядро «имя» | ядро «употребление» | пометка |",
        "|---|---:|---|---:|---|---|---|",
    ]
    for r in ряды_мн:
        lines.append(
            f"| `{r['мнемоника']}` | {r['встреч']} | {r['предложенный_класс'] or '—'} | {r['уверенность']:.3f} | "
            f"{r['ядро_имя']} ({r['p_имя']:.3f}) | {r['ядро_употребление']} ({r['p_употребление']:.3f}) | {r['пометка'] or 'согласие'} |"
        )
    lines += [
        "",
        "## Допущения латентности",
        "",
        "Зазор — минимум `такт потребителя − такт производителя` по парам dst/srcs внутри функции,",
        "без перехода через границу цикла. Настоящая латентность не больше этого минимума.",
        "Опровергнуто: допущение больше минимума и пар ≥ 3. Сомнительно: минимум больше допущения",
        "(компилятор ни разу не сжал до допущения). Мало данных: пар < 3.",
        "Колонка «по руководству» — раздел 6.1 руководства МЦСТ, выпуск 1.2, CC BY 4.0;",
        "числа про **Е4С/Е8С, не e2k-v6**. Глава 12 даёт задержки пар, не класс; где класса в 6.1 нет — пусто.",
        "",
        "| класс | допущение | пар | мин. зазор | вердикт | по руководству (Е4С/Е8С) |",
        "|---|---:|---:|---:|---|---|",
    ]
    for r in ряды_лат:
        зазор = "—" if r["мин_зазор"] is None else str(r["мин_зазор"])
        lines.append(
            f"| `{r['класс']}` | {r['допущение']} | {r['пар']} | {зазор} | {r['вердикт']} | {r['по_руководству']} |"
        )
    опровергнуты = [r["класс"] for r in ряды_лат if r["вердикт"] == "опровергнуто"]
    сомнительные = [r["класс"] for r in ряды_лат if r["вердикт"] == "сомнительно"]
    lines += [
        "",
        f"Опровергнуты: {', '.join(опровергнуты) if опровергнуты else 'нет'}.",
        f"Сомнительны: {', '.join(сомнительные) if сомнительные else 'нет'}.",
        "",
    ]
    return "\n".join(lines)


