# -*- coding: utf-8 -*-
"""Оценка ядер выбора группы и их перекрёстной проверки.

    python3 -m nnl_vliw.оценка --метки <папка с *.labels.jsonl> [--наборы eval_hard,eval_wide,eval_real]

Ядра загружаются через Матплату NNL (проверка sha256 паспорта, архитектура `мешок_шина`), а композиция
считается теми же формулами, что в обучении: проход 1 (блоки пишут понятия), смешивание по среднему,
проход 2 (блоки читают шину), общий softmax по «ничего» и ответам всех блоков.

Политики (на каждом графе; везде сначала считается жадный, итог — лучшее из жадного и выбранной группы):
  жадный        всегда только жадный;
  эвристика     нет делителей -> жадный, есть -> весь портфель (простое правило без обучения);
  ядро А / Б    группа, названная ядром; «ничего» -> весь портфель;
  перекрёсток   если ядра А и Б назвали одну группу — её, иначе весь портфель;
  оракул        самая дешёвая группа, достигающая лучшего.
Мера качества — лишние такты относительно полного портфеля (0 = как весь портфель) и доля графов,
на которых пришлось запускать весь портфель (чем меньше, тем больше сэкономлено).
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

from . import данные as Д
from . import ядра as Я
from .NNL.матплата import Матплата
from .язык import ЯзыкГрафов

КОРЕНЬ = Path(__file__).resolve().parent


def загрузить_ядро(папка, язык=None) -> Матплата:
    """Матплата со всеми блоками из <папка>/<блок>/ (паспорт.json + веса.npz)."""
    плата = Матплата(язык or ЯзыкГрафов(), str(КОРЕНЬ / "архитектуры"))
    for bd in sorted(p for p in Path(папка).iterdir() if (p / "паспорт.json").exists()):
        ok, res = плата.подключить(str(bd))
        if not ok:
            raise RuntimeError(f"блок {bd.name}: {res}")
    return плата


def вероятности(плата: Матплата, токены: list[str]) -> dict:
    """Композиция ядра: {ответ: вероятность}, ключ «ничего» — вероятность «не знаю»."""
    блоки = list(плата.блоки.values())
    запись: dict = {}
    for b in блоки:
        for k, v in b.arch.проход1(b.obj, токены).items():
            запись.setdefault(k, []).append(v)
    шина = {k: sum(v) / len(v) for k, v in запись.items()}
    логиты = {"ничего": 0.0}
    for b in блоки:
        логиты.update(b.arch.проход2(b.obj, токены, шина))
    m = max(логиты.values())
    e = {k: math.exp(v - m) for k, v in логиты.items()}
    z = sum(e.values())
    return {k: v / z for k, v in e.items()}


def решение(p: dict, порог: float = 0.0):
    """(группа или None, вероятность выбранного). None — «не знаю»: запустить портфель целиком."""
    k = max(p, key=p.get)
    if k == "ничего" or p[k] < порог:
        return None, p[k]
    return Я.группа_из_ответа(k), p[k]


def мс(r: dict, группа: str) -> int:
    """Итог при запуске жадного и группы: лучшее из двух (нет группы -> жадный)."""
    g = r["по_группам"]["greedy"]
    v = r["по_группам"].get(группа)
    return g if v is None else min(g, v)


def политики(база: list[dict], A: Матплата, Б: Матплата, порог: float = 0.0) -> dict:
    rows = []
    for r in база:
        a, pa = решение(вероятности(A, r["токены"]), порог)
        b, pb = решение(вероятности(Б, r["токены"]), порог)
        rows.append((r, a, b, pa, pb))
    n = len(rows)

    def свод(выбор):
        """выбор(r, a, b) -> группа или None (весь портфель)."""
        лишних = верно = полный = 0
        for r, a, b, *_ in rows:
            g = выбор(r, a, b)
            if g is None:
                полный += 1
                continue
            m = мс(r, g)
            лишних += m - r["лучший"]
            верно += int(m == r["лучший"])
        отв = n - полный
        return {"лишних_тактов": лишних, "полный_портфель": round(полный / n, 4),
                "верно_среди_отвеченных": round(верно / отв, 4) if отв else None}

    out = {"графов": n, "лучший_итог": sum(r["лучший"] for r, *_ in rows),
           "трудных": sum(1 for r, *_ in rows if r["дешёвая"] != "greedy")}
    out["жадный"] = свод(lambda r, a, b: "greedy")
    out["эвристика"] = свод(lambda r, a, b: None if r["понятия"]["деления:есть"] == 1.0 else "greedy")
    out["ядро А"] = свод(lambda r, a, b: a)
    out["ядро Б"] = свод(lambda r, a, b: b)
    out["перекрёсток"] = свод(lambda r, a, b: a if (a is not None and a == b) else None)
    out["оракул"] = свод(lambda r, a, b: r["дешёвая"])
    # согласие как сигнал ошибки: точность ядра А там, где ядра согласны, и там, где нет
    согл = [(r, a) for r, a, b, *_ in rows if a is not None and a == b]
    расх = [(r, a) for r, a, b, *_ in rows if a is not None and a != b]

    def точн(л):
        return round(sum(1 for r, a in л if мс(r, a) == r["лучший"]) / len(л), 4) if л else None
    out["согласие"] = {"согласны": len(согл), "расходятся": len(расх),
                       "ядро А верно при согласии": точн(согл), "ядро А верно при расхождении": точн(расх)}
    # честная база для перекрёстной проверки: отказ наугад при той же доле запусков портфеля
    # (ожидание: каждый граф уходит в портфель с вероятностью доли, остальные решает ядро А)
    доля = out["перекрёсток"]["полный_портфель"]
    out["случайный отказ"] = {"полный_портфель": доля, "лишних_тактов": round((1 - доля) * out["ядро А"]["лишних_тактов"], 1)}
    # отказ по уверенности одного ядра (то, что делает селективный решатель NNL): p выбранного ответа < порога
    кривая = []
    for т in (0.3, 0.4, 0.5, 0.6, 0.7, 0.8):
        лишних = полный = 0
        for r, a, b, pa, pb in rows:
            if a is None or pa < т:
                полный += 1
            else:
                лишних += мс(r, a) - r["лучший"]
        кривая.append({"порог": т, "полный_портфель": round(полный / n, 4), "лишних_тактов": лишних})
    out["уверенность ядра А"] = кривая
    # сколько трудных графов ядро А/Б не отдало жадному (полнота по трудным)
    труд = [(r, a, b) for r, a, b, *_ in rows if r["дешёвая"] != "greedy"]
    out["трудные: не оставлено жадному"] = {
        "ядро А": round(sum(1 for r, a, b in труд if a != "greedy") / len(труд), 4) if труд else None,
        "ядро Б": round(sum(1 for r, a, b in труд if b != "greedy") / len(труд), 4) if труд else None,
        "перекрёсток": round(sum(1 for r, a, b in труд if not (a == "greedy" and b == "greedy")) / len(труд), 4) if труд else None}
    return out


def печать(имя: str, o: dict) -> None:
    print(f"\n== {имя}: графов {o['графов']}, трудных (жадного мало) {o['трудных']}")
    print(f"   {'политика':14}{'лишних тактов':>15}{'весь портфель':>15}{'верно из отвеченных':>21}")
    for k in ("жадный", "эвристика", "ядро А", "ядро Б", "перекрёсток", "оракул"):
        v = o[k]
        ов = "—" if v["верно_среди_отвеченных"] is None else f"{v['верно_среди_отвеченных']:.3f}"
        print(f"   {k:14}{v['лишних_тактов']:>15}{v['полный_портфель']:>15.3f}{ов:>21}")
    сл = o["случайный отказ"]
    print(f"   {'случайный отказ':14}{сл['лишних_тактов']:>15}{сл['полный_портфель']:>15.3f}{'(то же число запусков портфеля, что у перекрёстка)':>21}")
    print("   отказ по уверенности ядра А (порог p -> доля портфеля / лишних тактов): " +
          "; ".join(f"{k['порог']}: {k['полный_портфель']:.2f}/{k['лишних_тактов']}" for k in o["уверенность ядра А"]))
    c = o["согласие"]
    print(f"   ядра согласны на {c['согласны']}, расходятся на {c['расходятся']}; верность ядра А: "
          f"при согласии {c['ядро А верно при согласии']}, при расхождении {c['ядро А верно при расхождении']}")
    t = o["трудные: не оставлено жадному"]
    print(f"   трудные графы, не оставленные жадному: А {t['ядро А']}, Б {t['ядро Б']}, перекрёсток {t['перекрёсток']}")


def main() -> int:
    for _s in (sys.stdout, sys.stderr):
        try:
            _s.reconfigure(errors="replace", encoding="utf-8")
        except Exception:  # noqa: BLE001
            pass
    ap = argparse.ArgumentParser(description="Оценка ядер выбора группы портфеля")
    ap.add_argument("--метки", required=True)
    ap.add_argument("--блоки", default=str(КОРЕНЬ / "блоки"))
    ap.add_argument("--наборы", default="eval_hard,eval_wide,eval_real")
    ap.add_argument("--порог", type=float, default=0.0)
    ap.add_argument("--json")
    a = ap.parse_args()
    A, Б = загрузить_ядро(Path(a.блоки) / "А"), загрузить_ядро(Path(a.блоки) / "Б")
    print("ядро А:", {n: b.чисел for n, b in A.блоки.items()}, "| ядро Б:", {n: b.чисел for n, b in Б.блоки.items()})
    язык = ЯзыкГрафов()
    итог = {}
    for имя in a.наборы.split(","):
        база = Д.с_токенами(Д.прочитать_метки(Path(a.метки) / f"{имя}.labels.jsonl"), язык)
        итог[имя] = политики(база, A, Б, a.порог)
        печать(имя, итог[имя])
    if a.json:
        Path(a.json).write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
