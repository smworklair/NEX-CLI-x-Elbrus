# -*- coding: utf-8 -*-
"""Язык ядра NEX: граф команд ↔ токены без потерь.

Блоку-планировщику нужен сам граф, а не его сводка (мешок токенов теряет рёбра), поэтому токены здесь
несут граф целиком: «профиль:<имя>», «у:<номер>:<операция>» и «р:<номер>:<предок>» на каждое ребро.
Блоки с мешком токенов (как в nnl_vliw) в это ядро ставятся через архитектуру, которая отбирает свои токены.
"""

from __future__ import annotations

ИМЯ = "NEX-граф"
ВЕРСИЯ = "1.0"
ПРОФИЛЬ_ПО_УМОЛЧАНИЮ = "e2k-v6-measured"


def текст_из_dag(dag, model) -> str:
    """Граф и профиль машины → запрос ядру (тот же формат, что training/encode.encode_prompt)."""
    строки = [f"профиль: {model.name}", "граф:"]
    for ins in dag:
        предки = " ".join(str(p) for p in ins.preds)
        строки.append(f"{ins.id} {ins.op}" + (f" <- {предки}" if предки else ""))
    return "\n".join(строки)


class ЯзыкГрафа:
    """Объект «язык» для матплаты: `язык.перевести(текст) -> {"токены": [...], "понятия": {}}`."""

    имя = ИМЯ
    версия = ВЕРСИЯ

    def перевести(self, текст: str) -> dict:
        профиль = ПРОФИЛЬ_ПО_УМОЛЧАНИЮ
        узлы, рёбра = [], []
        for строка in текст.splitlines():
            строка = строка.strip()
            if строка.startswith("профиль:"):
                профиль = строка.split(":", 1)[1].strip() or профиль
                continue
            if not строка or строка in ("граф:", "расписание:"):
                continue
            части = строка.split()
            try:
                номер = int(части[0])
            except ValueError:
                continue
            узлы.append(f"у:{номер}:{части[1] if len(части) > 1 else 'ADD'}")
            if "<-" in части:
                for p in части[части.index("<-") + 1:]:
                    рёбра.append(f"р:{номер}:{int(p)}")
        return {"токены": [f"профиль:{профиль}"] + узлы + рёбра, "понятия": {}}

    def паспорт_языка(self) -> dict:
        return {"имя": ИМЯ, "версия": ВЕРСИЯ, "токены": ["профиль:", "у:", "р:"]}


def текст_из_токенов(токены: list[str]) -> tuple[str, str]:
    """Обратный перевод: (текст графа в формате encode_prompt, имя профиля)."""
    профиль = ПРОФИЛЬ_ПО_УМОЛЧАНИЮ
    операции: dict[int, str] = {}
    предки: dict[int, list[int]] = {}
    for t in токены:
        if t.startswith("профиль:"):
            профиль = t.split(":", 1)[1]
        elif t.startswith("у:"):
            _, i, op = t.split(":", 2)
            операции[int(i)] = op
        elif t.startswith("р:"):
            _, i, p = t.split(":", 2)
            предки.setdefault(int(i), []).append(int(p))
    строки = [f"профиль: {профиль}", "граф:"]
    for i in sorted(операции):
        р = предки.get(i, [])
        строки.append(f"{i} {операции[i]}" + (" <- " + " ".join(str(x) for x in р) if р else ""))
    return "\n".join(строки), профиль
