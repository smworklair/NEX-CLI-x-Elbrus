# -*- coding: utf-8 -*-
"""Собрать папку блока «планировщик»: веса.npz (имена и sha256 файлов крошек) и паспорт.json.

    python3 -m nex_core.собрать_блок
Переобучили крошки — запустите снова, иначе блок не подключится (sha256 не совпадёт).
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

КОРЕНЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(КОРЕНЬ.parent))
from nex_core.архитектуры import планировщик as П  # noqa: E402
from nex_core.язык import ЯзыкГрафа  # noqa: E402

ПАПКА = КОРЕНЬ / "блоки" / "планировщик"


def main() -> int:
    ПАПКА.mkdir(parents=True, exist_ok=True)
    файлы = П.файлы_крошек()
    np.savez(ПАПКА / "веса.npz", файлы=np.array([f.name for f in файлы]),
             sha256=np.array([П._sha256(f) for f in файлы]))
    w = ПАПКА / "веса.npz"
    obj = П.загрузить(str(w), {})
    п, ч = "планировщик:граница", "планировщик:выигрыш_крошек"
    проекции = {
        "граница_достигнута": {п: 16.0, ч: -16.0},
        "крошки_лучше_baseline": {п: -16.0, ч: 16.0},
        "крошки_вровень": {п: -16.0, ч: -16.0},
    }
    паспорт = {
        "имя": "планировщик", "версия": 1,
        "роль": "составной блок: крошки + правило границы; строит расписание и говорит, есть ли смысл искать дальше",
        "архитектура": "планировщик",
        "настройки": {"состав": ["крошки (vliw/tiny)", "правило границы"], "веса_крошек": [f.name for f in файлы]},
        "веса": {"файл": "веса.npz", "sha256": hashlib.sha256(w.read_bytes()).hexdigest(), "чисел": П.чисел(obj)},
        "язык": ЯзыкГрафа().паспорт_языка(),
        "пишет": [п, ч], "читает": [], "ответы": list(П.ОТВЕТЫ), "проекции": проекции,
    }
    (ПАПКА / "паспорт.json").write_text(json.dumps(паспорт, ensure_ascii=False, indent=1), encoding="utf-8")
    print("готово:", ПАПКА, "чисел:", паспорт["веса"]["чисел"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
