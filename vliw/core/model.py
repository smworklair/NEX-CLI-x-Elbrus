# ОПРОВЕРГНУТЫЙ профиль первой версии. Оставлен НАМЕРЕННО, а не забыт: на нём
# видно, как одна неверно прочитанная проба меняет все выводы. Именно из него
# следовала «монополия умножителя», которой в железе нет.
