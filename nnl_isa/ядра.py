# -*- coding: utf-8 -*-
"""Два ядра NNL. Каждое — одна сеть из четырёх блоков, класс ровно в одном блоке.

Ядро «имя» режет классы по смыслу операции. Ядро «употребление» — по набору
каналов из профиля e2k-v6 (другое разбиение, другой размер вектора, другая соль).
Ответ блока — «<область>/<класс>». «Ничего» у сети общее и значит «не знаю».
"""

from __future__ import annotations

# класс -> блок. UNKNOWN — заглушка модели, примеров с такой меткой в обучении нет.
БЛОКИ_ИМЕНИ = {
    "имя_цел_пам": ("ADD", "SUB", "MUL", "DIV", "AND", "SHL", "LOAD", "STORE", "INSF", "MERGE", "COMBO"),
    "имя_дроб": ("FADD", "FMUL", "FMA", "FDIV", "CONV"),
    "имя_пред_упр": ("PRED", "RW", "UNKNOWN"),
    "имя_упак": ("PACK", "PACKLOG", "AAU", "MOVA", "MOVAQ", "INCR"),
}

# Набор каналов профиля (docs/ISA.md), не метка. UNKNOWN в модели — «любой канал».
БЛОКИ_УПОТРЕБЛЕНИЯ = {
    "упот_один": ("DIV", "FDIV", "RW"),                                  # один канал: 5 или 0
    "упот_память": ("STORE", "AAU", "LOAD", "MOVA", "MOVAQ"),            # каналы с 2 и/или 5, не «все шесть»
    "упот_четвёрка": ("MUL", "CONV", "INSF", "PACKLOG", "PRED", "PACK", "COMBO"),  # подмножество {0,1,3,4}
    "упот_все": ("ADD", "SUB", "AND", "SHL", "MERGE", "FADD", "FMUL", "FMA", "INCR", "UNKNOWN"),
}

# имя ядра -> (блоки, корзины, размер вектора, префикс соли)
ЯДРА = {
    "имя": (БЛОКИ_ИМЕНИ, 192, 24, "имя-соль"),
    "употребление": (БЛОКИ_УПОТРЕБЛЕНИЯ, 128, 32, "упот-соль"),
}

ПОТОЛОК_ЧИСЕЛ = 30_000


def классы_блока(ядро: str) -> dict[str, str]:
    """класс -> область (имя блока без префикса файла: ключ словаря)."""
    блоки = ЯДРА[ядро][0]
    out = {}
    for область, классы in блоки.items():
        for k in классы:
            if k in out:
                raise ValueError(f"класс {k} в двух блоках ядра {ядро}")
            out[k] = область
    return out


def область_класса(ядро: str, класс: str) -> str:
    return классы_блока(ядро)[класс]


def ответ_id(область: str, класс: str) -> str:
    return f"{область}/{класс}"


def класс_из_ответа(ответ: str) -> str:
    return ответ.rsplit("/", 1)[1]


def описание_блоков(ядро: str) -> list[dict]:
    блоки, B, d, соль0 = ЯДРА[ядро]
    области = list(блоки)
    out = []
    for i, (область, классы) in enumerate(блоки.items()):
        out.append({
            "имя": область,
            "область": область,
            "корзины": B,
            "размер": d,
            "соль": f"{соль0}-{i}-{область}",
            "пишет": [область],
            "читает": [x for x in области if x != область],
            "ответы": [ответ_id(область, k) for k in классы],
            "классы": list(классы),
        })
    return out


def числа_оценки(ядро: str) -> int:
    """Сколько чисел будет у ядра до обучения (те же формы, что у БлокУч)."""
    всего = 0
    for b in описание_блоков(ядро):
        W, R, Y = 1, len(b["читает"]), len(b["ответы"])
        всего += b["корзины"] * b["размер"] + b["размер"] * W + W + b["размер"] * Y + Y + 2 * R * Y
    return всего
