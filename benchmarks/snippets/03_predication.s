// Фрагмент 3. Предикатное выполнение: обе ветки считаются, запись разрешает предикат.
{
  // Сравниваем значения и пишем флаги в предикаты %pred0 и %pred1
  cmples,0 %r10, %r11, %pred0
  cmpgts,1 %r12, %r13, %pred1
  muls,2   %r14, %r15, %r20
  muls,3   %r16, %r17, %r21
}
{
  // Инструкции выполняются условно в зависимости от предикатов
  adds,0 %r20, %r21, %r30 ? %pred0
  subs,1 %r20, %r21, %r30 ? ~%pred0
  muls,2 %r20, %r12, %r31 ? %pred1
  adds,3 %r21, %r13, %r31 ? ~%pred1
}
{
  // Слияние веток в общий результат
  adds,0 %r30, %r31, %r40
}
