    ядра = ("имя", "употребление")
    ключ = {"имя": "токены_имени", "употребление": "токены_употребления"}
    копилка = {я: [] for я in ядра}
    истины = []
    пред_имя = []
    пред_упот = []
    пред_сосед = []
    пред_лог = {я: [] for я in ядра}
    по_фолдам = []
    for i, тест in enumerate(блоки):
        train = [r for j, b in enumerate(блоки) if j != i for r in b] + одиночные
        tr, dv = Д.обучение_и_dev(train, зерно=зерно + 17 + i)
        истины.extend(r["класс"] for r in тест)
        сос = ближайший(train, тест)
        пред_сосед.extend(сос)
        логи = {}
        for я in ядра:
            логи[я] = логрегрессия(train, тест, ключ[я])
            пред_лог[я].extend(логи[я])
        ответы = {}
        for j, я in enumerate(ядра):
            блоки_уч, итог = О.обучить_ядро(я, tr, dv, зерно=зерно * 10 + i * 2 + j + 1, выход=None,
                                            сведения={"фолд": i, "обучение": len(tr), "dev": len(dv)})
            сеть = _сеть(блоки_уч)
            колонка = []
            for r in тест:
                cls, _имя, p = О.решение(О.вероятности_сети(сеть, r[ключ[я]]))
                колонка.append(cls)
                копилка[я].append({"мнемоника": r["мнемоника"], "класс": r["класс"],
                                   "ответ": cls, "p": round(p, 4), "фолд": i})
            ответы[я] = колонка
