# -*- coding: utf-8 -*-
"""NNL (Neural Network Lego) — Слой 4: Ядро причинности (Causality Core).

Отвечает за проверку причинных связей между понятиями на шине:
  1. Не проверяет имена блоков через if/elif — работает исключительно с абстрактными понятиями шины.
  2. Проецирует локальные выводы блока в понятия шины так, как блок объявил в паспорте (поле `проекции`). Ядро не угадывает смысл ответа.
  3. Для блоков без объявленных проекций принимает необязательный провайдер приложения (метод `проекция(блок, ответ_id)`); без провайдера
     такой ответ ничего не проецирует.
  4. Проверяет согласованность графа понятий: группирует их по пространствам имён (часть понятия до «:»), объявленным в паспортах блоков,
     и не знает, что эти пространства значат.
"""

ПРЕФИКС_ВЫВОДА = "вывод_"      # понятия вида «вывод_<блок>:<ответ>» процессор пишет сам; всё остальное на шине — от паспортов блоков
ПРОЧИЕ = "прочие"              # пространство для понятий, чей префикс не объявлен ни в одном паспорте


def пространство(понятие):
    """Пространство имён понятия: часть до первого «:» (у понятия без «:» его нет)."""
    return понятие.split(":", 1)[0] if ":" in понятие else None


class ЯдроПричинности:
    def __init__(self, провайдер=None):
        if провайдер is not None and not hasattr(провайдер, "проекция"):
            raise TypeError("провайдер проекций должен иметь метод проекция(блок, ответ_id), получено: %r" % (провайдер,))
        self.провайдер = провайдер
        self.правила_совместимости = []

    def проецировать(self, блок, ответ_id):
        """Проекция подтверждённого ответа блока в понятия шины.
        1. Объявленная в паспорте блока — единственный источник по умолчанию.
        2. Нет в паспорте — спрашиваем провайдера приложения, если он подключён.
        """
        if ответ_id in блок.проекции:
            return dict(блок.проекции[ответ_id])
        if self.провайдер is not None:
            return dict(self.провайдер.проекция(блок, ответ_id))
        return {}

    def проверить_цепочку(self, отклики, шина, конфликты=None, пространства=None):
        """Проверяет причинную совместимость понятий на шине.
        Оперирует исключительно понятиями шины, не завязываясь на имена блоков и на смысл пространств имён.
        `пространства` — множество пространств, объявленных в паспортах блоков (матплата.пространства()); без него группируем по любому префиксу.
        """
        финал = dict(отклики)
        активные_понятия = list(шина.keys())

        выводы = [k for k in активные_понятия if k.startswith(ПРЕФИКС_ВЫВОДА)]
        группы = {}
        for k in активные_понятия:
            if k.startswith(ПРЕФИКС_ВЫВОДА):
                continue
            ns = пространство(k)
            if ns is None or (пространства is not None and ns not in пространства):
                ns = ПРОЧИЕ
            группы.setdefault(ns, []).append(k)

        цепочка = {
            "активные_выводы": выводы,
            "понятия_по_пространствам": группы,
            "число_фактов": len(активные_понятия),
            "статус": "согласовано" if any(ns != ПРОЧИЕ for ns in группы) else "изолировано",
            "конфликты": sorted(конфликты or []),
        }
        if конфликты:
            цепочка["статус"] = "есть конфликты"

        # Если какой-либо блок синтезировал живой ответ — сохраняем
        for имя, отклик in отклики.items():
            if isinstance(отклик, dict) and "живой_текст" in отклик:
                цепочка["живой_текст"] = отклик["живой_текст"]

        финал["_причинная_цепочка"] = цепочка
        return финал
