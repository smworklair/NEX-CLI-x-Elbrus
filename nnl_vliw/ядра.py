# -*- coding: utf-8 -*-
"""Два ядра NNL для выбора группы портфеля. Каждое ядро — матплата с двумя блоками.

Композиция одна: общий softmax по ответам обоих блоков плюс «ничего» (= «не знаю»,
запустить портфель целиком). Блоки делят между собой ОБЛАСТЬ графа, а не задачу:

  ядро А — по делителям:   блок «А_без_делений» (~100K чисел), блок «А_с_делениями» (~200K);
  ядро Б — по памяти:      блок «Б_много_памяти» (~100K), блок «Б_мало_памяти» (~200K).

Ответ блока — «<область>/<группа>», например «деления:есть/rule». Область строки считается из графа
(язык.понятия_графа), группа — самая дешёвая группа портфеля, достигающая его лучшего makespan
(tools/portfolio_labels.py). Ядра различаются разбиением, размером вектора токена и солью хеширования,
поэтому ошибаются по-разному; на этом держится их перекрёстная проверка (оценка.py).
"""

from __future__ import annotations

from .язык import ВСЕ_ПОНЯТИЯ  # noqa: F401

ГРУППЫ = ("greedy", "prio", "defer", "hold", "rule", "beam")

# понятие-область, имя блока, корзины, размер вектора, соль
ЯДРА = {
    "А": [("деления:нет", "А_без_делений", 2048, 48, "А1"),
          ("деления:есть", "А_с_делениями", 4096, 48, "А2")],
    "Б": [("память:много", "Б_много_памяти", 1536, 64, "Б1"),
          ("память:мало", "Б_мало_памяти", 3072, 64, "Б2")],
}


def область_строки(ядро: str, понятия: dict) -> str:
    """Какому блоку ядра принадлежит строка (по меткам понятий графа)."""
    for обл, *_ in ЯДРА[ядро]:
        if понятия.get(обл) == 1.0:
            return обл
    raise ValueError(f"строка не попала ни в одну область ядра {ядро}: {понятия}")


def ответ_id(область: str, группа: str) -> str:
    return f"{область}/{группа}"


def группа_из_ответа(ответ: str) -> str:
    return ответ.rsplit("/", 1)[1]


def описание_блоков(ядро: str) -> list[dict]:
    """[{имя, область, корзины, размер, соль, пишет, читает, ответы}] — устройство блоков ядра."""
    обл = [o for o, *_ in ЯДРА[ядро]]
    out = []
    for o, имя, B, d, соль in ЯДРА[ядро]:
        out.append({"имя": имя, "область": o, "корзины": B, "размер": d, "соль": соль,
                    "пишет": [o], "читает": [x for x in обл if x != o],
                    "ответы": [ответ_id(o, g) for g in ГРУППЫ]})
    return out
