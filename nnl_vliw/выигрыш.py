# -*- coding: utf-8 -*-
"""Два ядра NNL: «есть ли на этом участке что улучшать».

Задача другая, чем в ядрах выбора группы (ядра.py): не какую группу крошек запускать, а
стоит ли тратить на участок поиск вообще. Ответ блока — «<область>/выигрыш:есть» или
«<область>/выигрыш:нет»; «ничего» (= «не знаю») означает «искать как обычно».

Сначала точное правило без нейросети: если жадный уже на нижней границе (makespan = max(критический
путь, ресурсная граница)), выигрыша быть не может — это доказательство. Ядра отвечают только там, где
правило молчит, и получают зазор «жадный − граница» как токен.

Устройство то же: две матплаты по два блока, блоки делят ОБЛАСТЬ графа, ядра различаются
разбиением, размером вектора токена и солью. Метка берётся из портфеля крошек
(tools/portfolio_labels.py): «есть» — если лучший makespan портфеля короче жадного.

    python3 -m nnl_vliw.выигрыш обучить --метки <папка *.labels.jsonl> [--зерно 1]
    python3 -m nnl_vliw.выигрыш оценка  --метки <папка> --наборы eval_hard,eval_wide,eval_real

Для встраивания: `оценить(dag, model)` — один участок, `оценить_много(...)` — список участков.
"""

