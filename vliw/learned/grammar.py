"""Грамматика ответа для llama.cpp: скелет расписания вместо свободного текста.

ЗАЧЕМ. Замер `docs/DIAG3.md` показал главное: модель планирует хорошо, а
проваливается на оформлении. У адаптера прогона 1 из 98 законных ответов 97
были ТОЧНЫМ оптимумом — то есть когда он вообще выдавал разбираемое
расписание, оно почти всегда идеально. Штрафовали его за другое: за канал,
на котором операция не исполняется, и за поломанный формат. Убери эти два
способа провалиться — и на широком эвале выходит 84% законных против 15%
(адаптер прогона 2), из них 74% в точном оптимуме CP-SAT.

ПОЧЕМУ ГРАММАТИКА, А НЕ МАСКА ПО ЛОГИТАМ. На Kaggle то же самое сделано
маскированием логитов (`training/validate_kaggle.py`), но там transformers,
где логиты под рукой. Локально работает llama.cpp через сокет, логитов
наружу нет — зато есть GBNF: сервер сам не даст модели выйти за грамматику.
Гарантия та же самая, механизм другой.

ЧЕГО ГРАММАТИКА НЕ УМЕЕТ. Она описывает КАЖДУЮ строку по отдельности:
такт — любое число, канал — из исполнимых для этой операции. Она не знает,
что канал уже занят другой операцией В ЭТОМ ЖЕ ТАКТЕ, потому что это
зависит от уже сгенерированного, а не от позиции в скелете. Отсюда и
результат замера: незаконных каналов стало 0 (было 315), а конфликтов
БОЛЬШЕ (144 → 208) — выбор сузился, и двое чаще целятся в один канал.
Конфликты снимает `repair.py` паросочетанием, и в этом смысле грамматика и
починка не конкуренты, а половинки одного решения.
"""

from __future__ import annotations


def _escape(text: str) -> str:
    """Строковый литерал GBNF.

    Перевод строки обязан уехать как `\\n`, а не сырым байтом: сырой байт
    внутри кавычек GBNF не принимает, и сервер отвергает всю грамматику
    целиком — молча, ответом об ошибке разбора, а не подсказкой.
    """
    return (text.replace("\\", "\\\\")
                .replace('"', '\\"')
                .replace("\n", "\\n"))


def schedule_grammar(dag, model) -> str:
    """GBNF для ответа на конкретный граф.

    Формат совпадает с обучающим до символа: `\\nID: такт=N канал=K`,
    строки подряд, завершающего перевода строки нет.

    Каналы берутся из модели машины — по одной строке грамматики на
    операцию, потому что у разных классов они разные: у STORE это `,2 ,5`,
    у деления только `,5`, у сложения все шесть. Один общий набор цифр
    вернул бы ровно ту ошибку, ради которой всё затевалось.
    """
    lines = []
    rules = []
    for idx, ins in enumerate(dag.instrs):
        chans = model.channels_for(ins.op)
        if not chans:
            # Класс, которого нет в профиле машины. Пусть выбирает любой —
            # грамматика не место для отказа, её задача сузить, а не решать.
            chans = tuple(range(model.width))
        alts = " | ".join(f'"{c}"' for c in sorted(chans))
        name = f"op{idx}"
        rules.append(
            f'{name} ::= "{_escape(chr(10) + str(ins.id) + ": такт=")}" '
            f'cycle " канал=" ({alts})')
        lines.append(name)

    body = " ".join(lines)
    return "\n".join([
        f"root ::= {body}",
        # Такт — число без ведущих нулей, но «0» само по себе законно.
        'cycle ::= "0" | [1-9] [0-9]*',
        *rules,
    ])


def grammar_stats(dag, model) -> dict:
    """Насколько грамматика сужает выбор — для отчёта, не для решения."""
    total = sum(len(model.channels_for(i.op)) or model.width
                for i in dag.instrs)
    return {
        "операций": len(dag.instrs),
        "вариантов канала всего": total,
        "было бы без грамматики": len(dag.instrs) * model.width,
    }
