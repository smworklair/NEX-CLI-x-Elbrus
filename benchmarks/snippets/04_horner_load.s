{
  ldw,0  [%r10 + 0], %r20
  ldw,2  [%r10 + 4], %r21
  adds,1 %r10, 8, %r10
}
{
  ldw,0  [%r10 + 0], %r22
  ldw,2  [%r10 + 4], %r23
  muls,1 %r30, %r20, %r40
}
{
  adds,0 %r40, %r21, %r41
  muls,1 %r30, %r30, %r31 // x^2
}
{
  muls,0 %r41, %r31, %r42
  muls,1 %r30, %r22, %r43
}
{
  adds,0 %r43, %r23, %r44
}
{
  adds,0 %r42, %r44, %r45
}
